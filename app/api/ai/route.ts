/* ========================================
   CLAUDE
======================================== */

async function askClaude({
  userMessage,
  history,
  clientContext,
}: {
  userMessage: string;
  history: HistoryMessage[];
  clientContext: string;
}) {
  /*
    Оставляем достаточно истории,
    чтобы Claude понимал контекст,
    но не отправляем бесконечный чат.
  */
  const conversation = history
    .filter(
      (item) =>
        (item.role === "user" ||
          item.role === "assistant") &&
        typeof item.text === "string" &&
        item.text.trim().length > 0,
    )
    .slice(-16)
    .map((item) => ({
      role: item.role,
      content: item.text
        .trim()
        .slice(0, 4000),
    }));

  conversation.push({
    role: "user",
    content: userMessage.slice(0, 6000),
  });

  const response = await fetch(
    "https://api.anthropic.com/v1/messages",
    {
      method: "POST",

      headers: {
        "Content-Type": "application/json",
        "x-api-key": anthropicApiKey,
        "anthropic-version": "2023-06-01",
      },

      body: JSON.stringify({
        model: anthropicModel,

        /*
          Обычно ответы будут короткими благодаря
          system prompt, но Claude сможет дать
          нормальный подробный ответ по запросу.
        */
        max_tokens: 1200,

        system: `${companyPrompt}

==================================================
ДАННЫЕ КЛИЕНТА
==================================================

${clientContext}`,

        messages: conversation,
      }),
    },
  );

  if (!response.ok) {
    const errorText =
      await response.text();

    console.error(
      "Anthropic API error:",
      response.status,
      errorText,
    );

    throw new Error(
      `Anthropic error: ${response.status}`,
    );
  }

  const data = (await response.json()) as {
    content?: Array<{
      type: string;
      text?: string;
    }>;
  };

  const reply =
    data.content
      ?.filter(
        (item) =>
          item.type === "text" &&
          typeof item.text === "string",
      )
      .map((item) => item.text)
      .join("\n")
      .trim() || "";

  return (
    reply ||
    "Не смог нормально ответить. Попробуй ещё раз."
  );
}

/* ========================================
   API ROUTE
======================================== */

export async function POST(
  request: NextRequest,
) {
  try {
    const body =
      (await request.json()) as {
        message?: string;
        history?: HistoryMessage[];
      };

    const message =
      body.message?.trim();

    if (!message) {
      return NextResponse.json(
        {
          error: "Введите сообщение",
        },
        {
          status: 400,
        },
      );
    }

    /* ====================================
       AUTH
    ==================================== */

    const authorization =
      request.headers.get(
        "authorization",
      );

    const accessToken =
      authorization?.startsWith(
        "Bearer ",
      )
        ? authorization.slice(7)
        : null;

    let clientContext = `
Пользователь не авторизован.

Ты НЕ имеешь доступа к его:
— заказам
— трек-кодам
— персональному коду
— задолженности
— весу посылок

Если он спрашивает персональные данные заказа,
коротко объясни, что нужно войти в аккаунт.
`.trim();

    /* ====================================
       CLIENT DATA
    ==================================== */

    if (accessToken) {
      const {
        data: { user },
        error: userError,
      } =
        await supabase.auth.getUser(
          accessToken,
        );

      if (userError) {
        console.error(
          "Supabase user error:",
          userError,
        );
      }

      if (user) {
        const {
          data: client,
          error: clientError,
        } = await supabase
          .from("clients")
          .select(
            "client_code, first_name, last_name",
          )
          .eq("user_id", user.id)
          .maybeSingle();

        if (clientError) {
          console.error(
            "Client lookup error:",
            clientError,
          );
        }

        if (client) {
          const {
  data: shipments,
  error: shipmentsError,
} = await supabase
  .from("shipments")
  .select(
    "tracking_code, status, weight, chargeable_weight, delivery_cost, final_amount, created_at, updated_at"
  )
  .eq("client_code", client.client_code)
  .order("created_at", {
    ascending: false,
  })
  .limit(10);

          if (shipmentsError) {
            console.error(
              "Shipment lookup error:",
              shipmentsError,
            );
          }

          const shipmentLines =
            shipments &&
            shipments.length > 0
              ? shipments
                  .map((shipment) => {
                    const weight =
                      shipment
                        .chargeable_weight ??
                      shipment.weight ??
                      "не указан";

                    const amount =
                      shipment.final_amount ??
                      shipment.delivery_cost ??
                      "не указано";

                    return [
                      `Трек-код: ${shipment.tracking_code}`,
                      `статус: ${shipment.status}`,
                      `вес: ${weight} кг`,
                      `к оплате: ${amount} сом`,
                    ].join(", ");
                  })
                  .map(
                    (line) => `- ${line}`,
                  )
                  .join("\n")
              : "Заказов пока нет.";

          const fullName = [
            client.first_name,
            client.last_name,
          ]
            .filter(Boolean)
            .join(" ");

          clientContext = [
            "Пользователь авторизован.",
            "",
            fullName
              ? `Имя: ${fullName}`
              : null,

            `Индивидуальный код клиента: ${client.client_code}`,

            "",
            "Последние заказы:",
            shipmentLines,
          ]
            .filter(
              (
                line,
              ): line is string =>
                typeof line === "string",
            )
            .join("\n");
        } else {
          clientContext = `
Пользователь авторизован, но профиль клиента Alakel не найден.

Не придумывай код или заказы.
`.trim();
        }
      }
    }

    /* ====================================
       CLAUDE
    ==================================== */

    const reply =
      await askClaude({
        userMessage: message,

        history: Array.isArray(
          body.history,
        )
          ? body.history
          : [],

        clientContext,
      });

    return NextResponse.json({
      ok: true,
      reply,
    });
  } catch (error) {
    console.error(
      "Alakel AI API error:",
      error,
    );

    return NextResponse.json(
      {
        error:
          "Помощник временно недоступен",
        reply:
          "Сейчас не могу ответить. Попробуй чуть позже.",
      },
      {
        status: 500,
      },
    );
  }
}